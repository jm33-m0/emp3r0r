// Package cagent holds build-time helpers for the C agent (core/c_agent).
package cagent

import (
	"fmt"
	"strings"
)

// EmbeddedConfigSource renders the C translation unit that defines the C
// agent's build-time data:
//
//	const uint8_t c2_embedded_config[]; // AES-GCM encrypted CBOR config
//	const size_t  c2_embedded_config_len;
//	const uint8_t c2_magic_string[];    // build-wide magic string (UTF-8)
//	const size_t  c2_magic_string_len;
//
// Both are emitted as byte arrays so arbitrary bytes survive untouched without
// any C string escaping. The C agent's Makefile compiles the result as an
// ordinary translation unit (CONFIG_SRC=...): there is no Python scaffold and
// no patchable ELF placeholder.
func EmbeddedConfigSource(configBlob []byte, magic string) []byte {
	var b strings.Builder
	b.WriteString("/* Generated by github.com/jm33-m0/emp3r0r/core/lib/cagent; do not edit. */\n")
	b.WriteString("#include \"c2_embedded_config.h\"\n\n")
	emitBytes(&b, "c2_embedded_config", configBlob)
	emitBytes(&b, "c2_magic_string", []byte(magic))
	return []byte(b.String())
}

// emitBytes writes a C byte array and its length. An empty slice emits {0} so
// the initializer is valid C99 while the exported length stays 0.
func emitBytes(b *strings.Builder, name string, data []byte) {
	fmt.Fprintf(b, "const uint8_t %s[] = {\n", name)
	if len(data) == 0 {
		b.WriteString("    0\n")
	} else {
		for i := 0; i < len(data); i += 12 {
			end := i + 12
			if end > len(data) {
				end = len(data)
			}
			b.WriteString("    ")
			for j, by := range data[i:end] {
				if j > 0 {
					b.WriteByte(' ')
				}
				fmt.Fprintf(b, "0x%02x,", by)
			}
			b.WriteByte('\n')
		}
	}
	fmt.Fprintf(b, "};\nconst size_t %s_len = %d;\n\n", name, len(data))
}
