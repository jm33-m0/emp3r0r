// Jobs holds all jobs, key is JobID
var Jobs sync.Map

// CreateJob creates a new job and saves it to Jobs map
func CreateJob(name, module, agentTag string) *def.Job {
	job := &def.Job{
		ID:       uuid.NewString(),
		Name:     name,
		AgentTag: agentTag,
		Module:   module,
		Created:  time.Now(),
		Status:   def.JobStatusPending,
	}

	Jobs.Store(job.ID, job)
	return job
}

// GetJob retrieves a job by ID
func GetJob(id string) *def.Job {
	if val, ok := Jobs.Load(id); ok {
		if job, ok := val.(*def.Job); ok && job != nil {
			return job
		}
	}
	return nil
}

// LogPath returns the on-disk log file for a job. The job ID is generated by
// CreateJob as a UUID, so callers that accept one from a remote operator must
// validate it before building a path.
func LogPath(jobID string) string {
	// Job IDs become file names. UUIDs and the server's socks5-<uuid> tokens
	// are single path components; anything else is refused rather than joined.
	if jobID == "" || jobID == "." || jobID == ".." ||
		strings.ContainsAny(jobID, `\/`) || filepath.Base(jobID) != jobID {
		return ""
	}
	return filepath.Join(live.EmpWorkSpace, "jobs", fmt.Sprintf("%s.log", jobID))
}

// HandleOutput appends output to a job's log file.
//
// The operator console creates the job record; the C2 server receives the
// agent's response and persists it. They are separate processes, so the server
// must not require a local GetJob entry before writing: the job ID is the
// correlation key, and the caller only passes IDs it has accepted.
func HandleOutput(jobID string, output []byte) {
	// Update LastSeen? No, that's done in AgentHandler

	// If job is "Foreground" (Interactive), usually handled by the caller of job (e.g., infinite loop in waiting)
	// But here we can log everything to file for persistence

	// Ensure job directory exists
	logPath := LogPath(jobID)
	if logPath == "" {
		return
	}
	jobDir := filepath.Dir(logPath)
	if _, err := os.Stat(jobDir); os.IsNotExist(err) {
		os.MkdirAll(jobDir, 0o700)
	}

	// Append to log file
	f, err := os.OpenFile(logPath, os.O_APPEND|os.O_CREATE|os.O_WRONLY, 0o600)
	if err == nil {
		defer f.Close()
		// Sanitize output before logging
		sanitizedOutput := util.StripANSI(string(output))
		f.WriteString(sanitizedOutput)
	}
}

// FinishJob records a job's terminal state. The stored value is replaced with
// an immutable copy: GetJob hands out the pointer, and readers must never see a
// half-written status. Unknown job IDs are ignored; the server may report a
// result for a job this process did not create.
func FinishJob(jobID string, err error) *def.Job {
	if jobID == "" {
		return nil
	}
	for {
		val, ok := Jobs.Load(jobID)
		if !ok {
			return nil
		}
		job, ok := val.(*def.Job)
		if !ok || job == nil {
			return nil
		}
		if job.Status == def.JobStatusCompleted || job.Status == def.JobStatusFailed {
			return job
		}
		finished := *job
		finished.Finished = time.Now()
		if err != nil {
			finished.Status = def.JobStatusFailed
			finished.Error = err.Error()
		} else {
			finished.Status = def.JobStatusCompleted
		}
		if Jobs.CompareAndSwap(jobID, val, &finished) {
			return &finished
		}
	}
}

// GetJobs returns a list of all jobs
func GetJobs() []*def.Job {
	var jobs []*def.Job
	Jobs.Range(func(key, value any) bool {
		if job, ok := value.(*def.Job); ok && job != nil {
			jobs = append(jobs, job)
		}
		return true
	})
	return jobs
}

