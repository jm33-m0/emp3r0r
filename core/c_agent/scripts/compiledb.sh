#!/bin/sh
# Build compile_commands.json for clangd.
#
# Bear 3 recognises compilers by executable path, and it has no concept of a
# compiler subcommand: it sees `zig cc` as zig with an ordinary argument.  A
# generated shim that already contains the `cc` subcommand turns the invocation
# into a plain compiler call, so Bear parses it with the GCC rules and inserts
# `-c` in the correct place for link commands.  Pointing Bear at zig directly
# would instead produce `zig -c cc ...` for link commands.
#
# Both the config and the shim are generated (and gitignored) because they
# contain the host-specific zig path.  Bear intercepts in preload mode because
# zig is not one of its wrapper-mode compiler names.
#
# Usage: scripts/compiledb.sh [make-target ...]   (default: lib agent)
#   ZIG=/path/to/zig   zig executable to record (default: zig)
#   BEAR=bear          Bear 3 executable        (default: bear)
set -eu
cd "$(dirname "$0")/.."

zig=${ZIG:-zig}
zig_path=$(command -v "$zig") || {
    echo "error: zig executable not found: $zig" >&2
    exit 1
}
case $zig_path in
    /*) ;;
    *) zig_path=$PWD/$zig_path ;;
esac
bear=${BEAR:-bear}
command -v "$bear" >/dev/null 2>&1 || {
    echo "error: Bear 3 executable not found: $bear" >&2
    exit 1
}

# Escape a path for a JSON string literal and for a single-quoted shell word.
# Whitespace is fine; quoting and backslashes are not.
json_escape() {
    printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g'
}
shell_escape() {
    printf '%s' "$1" | sed "s/'/'\\\\''/g"
}

wrapper="$PWD/.bear-zig-cc"
config=bear.config.json

{
    printf '#!/bin/sh\n'
    printf '# Generated by scripts/compiledb.sh; replaced on every run.\n'
    printf "exec '%s' cc \"\$@\"\n" "$(shell_escape "$zig_path")"
} > "$wrapper"
chmod +x "$wrapper"

{
    printf '{\n'
    printf '  "compilation": {\n'
    printf '    "compilers_to_recognize": [\n'
    printf '      { "executable": "%s" }\n' "$(json_escape "$wrapper")"
    printf '    ],\n'
    printf '    "compilers_to_exclude": []\n'
    printf '  },\n'
    printf '  "output": {\n'
    printf '    "content": {\n'
    printf '      "include_only_existing_source": true,\n'
    printf '      "duplicate_filter_fields": "file"\n'
    printf '    },\n'
    printf '    "format": {\n'
    printf '      "command_as_array": true,\n'
    printf '      "drop_output_field": false\n'
    printf '    }\n'
    printf '  }\n'
    printf '}\n'
} > "$config"

if [ "$#" -eq 0 ]; then
    set -- lib agent
fi

exec "$bear" --force-preload --config "$config" \
    --output compile_commands.json -- \
    make -B CC="$wrapper" HOSTCC="$wrapper" "$@"
